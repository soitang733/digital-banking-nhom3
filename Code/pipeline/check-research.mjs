import fs from 'node:fs';
import assert from 'node:assert/strict';
import {scoreReviewed,conversion} from './score-reviewed.mjs';
const research=JSON.parse(fs.readFileSync('pipeline/data/research.json','utf8'));
assert.equal(research.records.length,2100);assert.equal(new Set(research.records.map(r=>[r.bank,r.year,r.code].join('|'))).size,2100);
assert.equal(research.stats.scored,research.records.filter(r=>r.level!==null).length);
assert.equal(research.rubrics.length,140);assert(research.rubrics.every(r=>r.levels.length===5&&r.levels.every(t=>t.length>10)));
assert(research.rubrics.every(r=>r.levels.every(t=>!/\d\. Trụ cột/.test(t))));
assert(research.records.filter(r=>r.level!==null).every(r=>r.citations.length&&r.reason&&r.reviewer&&r.reviewDate));
assert(research.records.filter(r=>r.level===null&&!r.na).every(r=>r.status!=='Đã đối chiếu tài liệu'));
assert(research.summaries.every(r=>r.score===null));assert(research.reports.every(r=>r.pages>0));
const complete=Array.from({length:6},(_,pillar)=>({pillar,level:pillar,na:false}));
assert.equal(scoreReviewed(complete).score,Object.values(conversion).reduce((a,b)=>a+b,0)/6);
assert.equal(scoreReviewed(complete.map((r,i)=>i===0?{...r,level:null}:r)).score,null);
const withNA=[...complete,{pillar:0,level:null,na:true}];assert.equal(scoreReviewed(withNA).score,scoreReviewed(complete).score);assert.equal(scoreReviewed(withNA).coverage,100);
assert.equal(scoreReviewed(complete.map(r=>({...r,level:null,na:true}))).score,null);assert.equal(scoreReviewed(complete.map(r=>({...r,level:null,na:true}))).coverage,null);
assert.equal(scoreReviewed([...complete,{pillar:0,level:5,na:false}]).score,(50+0+25+50+75+100)/6);
assert.equal(scoreReviewed([...complete,{pillar:0,level:null,na:false}]).score,null);
console.log('PASS: 2100 unique annual records, source-backed decisions, 140 clean rubrics, NA denominator, missing values, zero conversion and equal pillar weights.');
